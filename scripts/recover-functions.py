# This script does NOT own src/recomp/gen/recomp_stubs_unresolved.c.
#
# That file, recomp_funcs.h, the recomp_NNNN.c chunks and the dispatch table are
# all written by one full translate_batch_split pass over the whole function
# database (tools/recomp/translator.py:1283). This script translates only the
# reviewed entries, so its lifter sees a handful of referenced calls where the
# full pass saw 541 -- and it used to strip every stub body from that file and
# refill it from its own tiny view.
#
# The result was a split generated tree: the header declared 541 unresolved
# stubs while the file that defines them held 3, and the link failed with
# LNK1120: 473 unresolved externals pointing at correct generated code. The 16
# identical orphan comments that accumulated in the stub file -- one per run, no
# bodies after any of them -- were the fossil of that clobbering.
#
# So the traps this script needs go to its own file, and the translator's stub
# file is left exactly as the full pass wrote it. Nothing here deletes a
# definition it did not create.
#
# Newly exposed direct calls must be linkable and fail visibly until reviewed.
# These are diagnostic traps, with no guessed stack cleanup or success return.
# Only the production tree may suppress a trap: focused fixtures deliberately
# hand-write counted seams for the same addresses (see tests/test_recovery_*.c),
# so scanning them here would drop traps the production build still needs.
#
# Two exclusions, both load-bearing:
#   - recomp_stubs_recovery.c is this script's own output. Counting its bodies
#     as "defined" would make the next run emit nothing and the traps would
#     vanish on the second run.
#   - gen/fixtures/ holds the fixture subset, which overlaps production on
#     purpose. A trap that only the fixture defines is still unresolved in the
#     game, and dropping it there is how sub_0018CEB0 and four others silently
#     lost their traps.
def _suppresses_a_trap(source):
    if source.name=='recomp_stubs_recovery.c':
        return True
    return 'fixtures' in source.parts

defined=set()
traps=set()
for source in (root/'src').rglob('*.c'):
    if _suppresses_a_trap(source):continue
    contents=source.read_text(encoding='utf-8')
    defined.update(re.findall(r'\bvoid\s+(\w+)\(void\)\s*\{',contents))
    traps.update(re.findall(r'\bvoid\s+(\w+)\(void\)\s*\{\s*recomp_icall_fail_log',contents))
missing={a:name for a,name in translator.lifter.referenced_calls.items() if name not in defined}
recovery_trap_lines=[]
if missing:
    recovery_trap_lines.append('/* Newly exposed recovery dependencies: diagnostic traps only. */')
    for address,name in sorted(missing.items()):
        recovery_trap_lines.append(f'void {name}(void) {{ recomp_icall_fail_log(0x{address:08X}u); abort(); }}')
recovery_trap_path=root/'src/recomp/gen/recomp_stubs_recovery.c'
recovery_trap_path.write_text(
    '/* Generated by scripts/recover-functions.py; traps for direct calls the reviewed\n'
    ' * recovery bodies expose that no production translation defines yet.\n'
    ' *\n'
    ' * Separate from recomp_stubs_unresolved.c on purpose: that file and\n'
    ' * recomp_funcs.h come from one full translate_batch_split pass and must stay\n'
    ' * consistent with each other. This script translates only the reviewed\n'
    ' * entries and cannot speak for the rest of the database. */\n'
    '#define RECOMP_GENERATED_CODE\n'
    '#include "recomp_funcs.h"\n'
    '#include <stdlib.h>\n\n'
    +('\n'.join(recovery_trap_lines) if recovery_trap_lines else '')
    +'\n',encoding='utf-8')
# The focused fixtures hand-write counted seams for a few of the same trap
# addresses, so linking the whole unresolved unit into a fixture target would
# collide.  Derive the complementary subset from the finished production trap
# set and leave the overlapping addresses to the fixtures.  Production keeps
# every trap.
#
# The production trap set is the union of two files that this script no longer
# conflates: the full pass's recomp_stubs_unresolved.c and this script's own
# recomp_stubs_recovery.c.  Read them back rather than trusting an in-memory
# variable, so the fixture subset always matches what the production target
# actually compiles.
# A focused fixture target links three things: the hand-written test, the
# generated body file for its unit, and this complement.  Both of the first two
# define symbols, so both must be subtracted -- scanning only tests/ missed the
# unit bodies and the fixture failed to link with
# LNK2005: sub_00191390 already defined in recovered_11c1_test.obj, because the
# unit file compiles the very bodies this complement was still trapping.
fixture_own=set()
for fixture in list((root/'tests').glob('test_recovery_*.c')) + \
        list((root/'src/recomp/recovered').glob('recovered_*_test.c')):
    fixture_own.update(re.findall(r'\bvoid\s+(\w+)\(void\)\s*\{',
                                  fixture.read_text(encoding='utf-8')))
def _keep(line):
    match=re.match(r'^void\s+(\w+)\(void\)\s*\{',line)
    return not (match and match.group(1) in fixture_own)
production_trap_lines=[]
for _trap_file in ('recomp_stubs_unresolved.c','recomp_stubs_recovery.c'):
    _p=root/'src/recomp/gen'/ _trap_file
    if _p.exists():
        production_trap_lines.extend(_p.read_text(encoding='utf-8').splitlines())
recovery_stubs=[line for line in production_trap_lines
                if _keep(line) and not line.startswith('/* Newly exposed recovery')]
already_trapped={re.match(r'^void\s+(\w+)',line).group(1)
                 for line in recovery_stubs
                 if re.match(r'^void\s+(\w+)\(void\)\s*\{',line)}
# A focused fixture compiles only its unit's bodies, so a callee that the
# production build resolves from another generated chunk -- or from a trap the
# production set already carries -- is still an undefined symbol there.  Emit a
# trap for every unit reference that no unit body defines, minus the ones the
# fixtures define themselves.  Production is unaffected: it links the real
# chunk and the full trap set.
unit_defined={int(e['start'],16) for e in entries}
fixture_refs=set()
for unit,addresses in test_units.items():
    for address in addresses:
        fixture_refs.update(re.findall(r'RECOMP_ABI_CALL\(0x([0-9A-Fa-f]{8})u',
                                       rendered[address][0]))
extra_traps=sorted(a for a in fixture_refs
                   if int(a,16) not in unit_defined
                   and f'sub_{a.upper()}' not in fixture_own
                   and f'sub_{a.upper()}' not in already_trapped)
if extra_traps:
    recovery_stubs.append('\n/* Callees this unit does not compile: trap only in the fixture. */')
    for address in extra_traps:
        recovery_stubs.append(f'void sub_{address.upper()}(void) {{ '
                              f'recomp_icall_fail_log(0x{address.upper()}u); abort(); }}')
# Written to its own subdirectory, NOT to src/recomp/gen/ directly.
#
# The production target globs src/recomp/gen/*.c into jsrf_recomp, so a fixture
# file left in that directory gets compiled into the game as well as into the
# recovery test. Once the clobbering fix let recomp_stubs_unresolved.c hold its
# real 274 stubs, every address this file also defines became a duplicate
# symbol: LNK2005 ... already defined in recomp_stubs_recovery_test.obj, dozens
# of them, then LNK1169. The fixture subset and the production set deliberately
# overlap, so the two must never be linked into one binary.
fixture_stub_dir=root/'src/recomp/gen/fixtures'

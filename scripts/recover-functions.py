    ' * recomp_stubs_unresolved.c into a fixture unit would collide with the\n'
    ' * counted seams those tests hand-write, so the overlapping addresses are\n'
    ' * dropped here and left to each fixture.  Production keeps every trap.\n'
    ' *\n'

source_header=['/* Generated by scripts/recover-functions.py; reviewed boundaries in config/recovered-functions.json. */',
        '#define RECOMP_GENERATED_CODE', '#include "../gen/recomp_types.h"',
        '#include <stdio.h>', '#include <stdlib.h>',
        'extern void xbox_outb(uint16_t port, uint8_t value);',
        'extern void xbox_outw(uint16_t port, uint16_t value);',
        'extern void xbox_outl(uint16_t port, uint32_t value);',
        'extern uint8_t xbox_inb(uint16_t port);',
        'extern uint16_t xbox_inw(uint16_t port);',
        'extern uint32_t xbox_inl(uint16_t port);']
declaration_names=set(translator.lifter.referenced_calls.values())
rendered={}
for entry in entries:
    address=int(entry['start'],16)
    code=translator.translate_function(address,database[address])
    if not code or '/* TODO:' in code: raise RuntimeError(f'Incomplete translation at {address:08X}')
    declaration_names.update(re.findall(r'\bsub_[0-9A-Fa-f]{8}\b', code))
    # The x86 IMUL destination is the low 32 bits of the product.  The
    # translator's signed C expression has undefined behavior on overflow;
    # preserve the guest operation with widened unsigned arithmetic before
    # the existing unsigned DIV sequence.  Keep this correction in the
    # generator so production and focused fixtures cannot diverge.
    if address == 0x00196800:
        code=code.replace(
            'eax = (uint32_t)((int32_t)eax * (int32_t)ecx);',
            'eax = (uint32_t)((uint64_t)(uint32_t)eax * (uint64_t)(uint32_t)ecx);')
        code=code.replace(
            'eax = (uint32_t)((int32_t)eax * (int32_t)edi);',
            'eax = (uint32_t)((uint64_t)(uint32_t)eax * (uint64_t)(uint32_t)edi);')
    if address == 0x00194210:
        # Production and focused fixtures both treat this INT3 as fatal.
        code=code.replace('/* int3: debug-trap slide byte, stepped over */',
                          'recomp_icall_fail_log(0x001942DFu); abort(); /* original INT3 */')
    if address == 0x00196C83:
        # x86 variable shifts use the low five bits of CL.  Keep the
        # raw-requested-channel path defined in host C for arg==32 while
        # retaining the original unmasked (arg << 6) slot address below.
        code=code.replace('edx = edx << LO8(ecx);',
                          'edx = edx << (LO8(ecx) & 31u);')
    # Public symbol is the checked wrapper, so direct calls are checked too.
    code=code.replace(f'void sub_{address:08X}(void)',f'static void body_{address:08X}(void)',1)
    stack_delta=4+entry.get('stack_args',0)
    restore_frame=entry.get('restore_frame_metadata',False)
    frame_check=' || g_ebp!=before_bp' if entry.get('kind','initializer')=='initializer' and not restore_frame else ''
    frame_save=', before_seh=g_seh_ebp' if restore_frame else ''
    frame_restore='\n    g_ebp=before_bp; g_seh_ebp=before_seh;' if restore_frame else ''
    wrapper=f'''void sub_{address:08X}(void) {{
    uint32_t before_stack=g_esp, before_bx=g_ebx, before_si=g_esi, before_di=g_edi, before_bp=g_ebp{frame_save};
    static RECOMP_TLS int logged;
    body_{address:08X}();{frame_restore}
    if (g_esp!=before_stack+{stack_delta} || g_ebx!=before_bx || g_esi!=before_si || g_edi!=before_di{frame_check}) {{
        fprintf(stderr,"[RECOVERED] ABI FAILURE 0x{address:08X} esp %08X->%08X expected +{stack_delta}; bx %08X->%08X si %08X->%08X di %08X->%08X bp %08X->%08X\\n",before_stack,g_esp,before_bx,g_ebx,before_si,g_esi,before_di,g_edi,before_bp,g_ebp); abort();
    }}
    if (!logged++) fprintf(stderr,"[RECOVERED] 0x{address:08X} returned; ABI verified (ESP/EBX/ESI/EDI)\\n");
}}'''
    rendered[address]=(code,wrapper)
declarations='\n'.join(f'extern void {name}(void);' for name in sorted(declaration_names))
chunks=source_header.copy()
for entry in entries:
    chunks.extend(rendered[int(entry['start'],16)])
chunks+=['recomp_func_t jsrf_lookup_recovered(uint32_t va) {','    switch (va) {']
for entry in entries:
    address=int(entry['start'],16)
    chunks.append(f'    case 0x{address:08X}u: return sub_{address:08X};')
chunks+=['    default: return 0;','    }','}']

def decision_cases(values):
    """Every `(name, recorded, want)` the guard MUST refuse.

    Built from the field list the module itself exports, so adding a deciding
    field to the schema automatically adds its mismatch and missing cases here.
    """
    cases = []
    for field in DECIDING_FIELDS:
        if field not in values:
            continue
        want = dict(values)
        want[field] = f'moved-{field}'
        cases.append((f'{field} differs', dict(values), want))
    for field in DECIDING_FIELDS:
        if field not in values:
            continue
        recorded = {k: v for k, v in values.items() if k != field}
        cases.append((f'{field} is missing', recorded, dict(values)))
    cases.append(('an unknown field', dict(values, extra_field='1'), dict(values)))
    return cases


def accepted(cases, compare):
    """The cases a `compare` implementation wrongly accepts."""
    return [name for name, recorded, want in cases if compare(recorded, want)[0]]


class SyntheticInputs:
    """A toolkit / tool / dxc triple to call the real `expected` against.

    The three translator sources and the tool are throwaway files: the fixtures
    exercise the guard's comparison, not the toolkit's contents, and the real
    toolkit is a sibling checkout that may be mid-edit.
    """

    def __init__(self, tmp, programs=126, distinct=126):
        self.dir = Path(tmp)
        toolkit = self.dir / 'toolkit'
        video = toolkit / 'src' / 'video'
        video.mkdir(parents=True)
        for name in prov.SOURCE_NAMES:
            (video / name).write_text(f'/* {name}, synthetic for the fixture */\n',
                                      encoding='utf-8')
        self.toolkit = toolkit
        self.tool = self.dir / 'nv2a_vsh_hlsl.exe'
        self.tool.write_bytes(b'MZ synthetic host tool\n')
        self.dxc = DXC
        self.values = prov.expected(toolkit, self.tool, DXC,
                                    programs=programs, distinct=distinct)


def corpus_c(values, *, body=None, count=None, define_count=True):
    """A `nv2a_vsh_programs.c` in the shape the generator emits.

    The count DEFINITION lives here (the `.h` only declares `extern`), which is what
    `check_corpus` reads, so `count`/`define_count` are the knobs the fixtures turn.
    `count` defaults to the block's own `distinct`, which is what the generator
    declares, so a matching corpus needs no extra argument.
    """
    block = prov.render_block(values) if body is None else body
    if count is None:
        count = values['distinct']
    lines = ['/*', ' * The NV2A ahead-of-time vertex-program corpus, synthetic.', ' *',
             block, ' */', '#include "nv2a_vsh_programs.h"', '']
    if define_count:
        lines.append(f'const size_t nv2a_vsh_program_count = {count};')
    lines.append('')
    return '\n'.join(lines)


def corpus_h(values, *, body=None, count=None):
    """A `nv2a_vsh_programs.h`: the same block, and only an `extern` declaration.

    `count` is not None only for the fixture that pins the `.c` as the file the
    count is read from -- a check that scanned the header would be vacuous.
    """
    block = prov.render_block(values) if body is None else body
    lines = ['/*', ' * The NV2A ahead-of-time vertex-program corpus header, synthetic.',
             ' *', block, ' */', '']
    if count is not None:
        lines.append(f'const size_t nv2a_vsh_program_count = {count};')
    lines.append('extern const size_t nv2a_vsh_program_count;')
    lines.append('')
    return '\n'.join(lines)


def write_corpus(parent, name, c_text=None, h_text=None):
    """A corpus DIRECTORY holding whichever of the two files `check_corpus` reads."""
    path = Path(parent) / name
    path.mkdir(parents=True, exist_ok=True)
    if c_text is not None:
        (path / 'nv2a_vsh_programs.c').write_text(c_text, encoding='utf-8')
    if h_text is not None:
        (path / 'nv2a_vsh_programs.h').write_text(h_text, encoding='utf-8')
    return path


def xbe_corpus_counts():
    """`(programs, distinct)` as `scripts/find-vertex-programs.py` measures the XBE.

    The generator passes its own measured counts into `expected`, so the corpus's
    recorded `programs`/`distinct` must equal what the scanner reports today; a
    scanner change is a corpus change and this is where it surfaces.  Measured:
    scanning the XBE alone gives 128 programs / 126 distinct, which is what
    `scripts/gen-shaders.py` reports for the whole `game/` tree, so the Media files
    contribute no record and the XBE alone reproduces the recorded counts.
    """
    fvp = load_module(SCRIPTS / 'find-vertex-programs.py', 'find_vertex_programs')
    data = XBE.read_bytes()
    sections = fvp.xbe_sections(data)
    found = fvp.scan_functions(data, 'default.xbe', sections, False)
    covered = [(f['offset'], f['offset'] + 4 + 16 * f['len']) for f in found]
    found += fvp.scan_referenced(data, 'default.xbe', sections, covered)
    by_words = {}
    for f in found:
        by_words.setdefault(f['words_digest'], f)
    return len(found), len(by_words)


def table_row_count(text):
    """The table's row count, read out of the generated C the way a reader would."""
    body = re.search(r'nv2a_vsh_programs\[\]\s*=\s*\{(.*?)\n\};', text, re.S)
    if not body:
        return None
    return len(re.findall(r'vp_words_[0-9A-Fa-f]{8}', body.group(1)))


def _block_line(line, field):
    """True when `line` records `field` inside the block (comment decoration stripped)."""
    return line.strip().lstrip('*/ ').startswith(field + ' = ')


def with_field(text, field, value):
    """`text` with `field`'s recorded value replaced -- the corpus's own bytes otherwise."""
    out, inside = [], False
    for line in text.splitlines():
        if prov.BEGIN_MARK in line:
            inside = True
        if inside and _block_line(line, field):
            out.append(f'{line[:len(line) - len(line.lstrip())]}{field} = {value}')
        else:
            out.append(line)
        if prov.END_MARK in line:
            inside = False
    return '\n'.join(out)


def without_field(text, field):
    """`text` with `field`'s line removed, inside the block only.

    `render_block` refuses to render an incomplete schema (that is its own guard),
    so a "missing field" corpus has to be built by taking a complete one apart.
    """
    out, inside, dropped = [], False, 0
    for line in text.splitlines():
        if prov.BEGIN_MARK in line:
            inside = True
        if inside and _block_line(line, field):
            dropped += 1
            continue
        out.append(line)
        if prov.END_MARK in line:
            inside = False
    assert dropped == 1, f'expected exactly one recorded line for {field!r}, removed {dropped}'
    return '\n'.join(out)


def duplicate_field(text, field):
    """`text` with `field`'s recorded line repeated, inside the block only.

    The second value is the same, so the block stays complete and self-consistent:
    the ONLY thing wrong with it is the duplication, which is what makes the
    malformed-block fixture isolate `parse_block`'s duplicate-key refusal instead
    of also failing a field comparison.
    """
    out, inside, copied = [], False, 0
    for line in text.splitlines():
        if prov.BEGIN_MARK in line:
            inside = True
        if inside and _block_line(line, field):
            out.append(line)
            out.append(line)
            copied += 1
            continue
        out.append(line)
        if prov.END_MARK in line:
            inside = False
    assert copied == 1, f'expected exactly one recorded line for {field!r}, copied {copied}'
    return '\n'.join(out)


class ProvenanceBase(unittest.TestCase):
    """A synthetic matching corpus directory, shared by the refusal classes."""

    programs = 126
    distinct = 126

    # Subclasses replace these; the base has none, so `mutation_table` on the base
    # itself raises rather than silently mutating nothing.
    MUTATIONS = {}
    ACCEPTANCE_MUTATIONS = {}

    @classmethod
    def setUpClass(cls):
        cls._tmp = tempfile.TemporaryDirectory(prefix='jsrf-r1-prov-')
        cls.inputs = SyntheticInputs(cls._tmp.name, cls.programs, cls.distinct)
        cls.values = cls.inputs.values
        cls.block = prov.render_block(cls.values)

    @classmethod
    def tearDownClass(cls):
        cls._tmp.cleanup()

    def mutation_table(self, mutation):
        """`[(anchor, replacement)]` for `mutation`; subclasses own their tables."""
        if mutation in self.ACCEPTANCE_MUTATIONS:
            return self.ACCEPTANCE_MUTATIONS[mutation]
        return self.MUTATIONS[mutation]

    def mutant(self, mutation):
        """`(module, path)` for a SCRATCH copy carrying `mutation`.

        The repository file is only ever READ: the mutant is written into the
        fixture's temp dir and loaded as its own module, so the case tables run
        against real, separate code.
        """
        source = SHIPPED.read_text(encoding='utf-8')
        for old, new in self.mutation_table(mutation):
            self.assertEqual(source.count(old), 1,
                             f'the mutation anchor for {mutation!r} is no longer unique '
                             f'({source.count(old)} occurrences); the module changed shape '
                             f'and this fixture must follow it')
            source = source.replace(old, new)
        path = Path(self._tmp.name) / (re.sub(r'\W+', '_', mutation) + '.py')
        path.write_text(source, encoding='utf-8')
        return load_module(path, 'vsh_aot_provenance_mutant'), path

    def corpus(self, name, c=MISSING, h=MISSING):
        """A corpus directory named `name`; `c`/`h` default to the matching pair."""
        return write_corpus(self._tmp.name, name,
                            corpus_c(self.values) if c is MISSING else c,
                            corpus_h(self.values) if h is MISSING else h)

    def check(self, corpus, want=None):
        """The production entry point, on a directory."""
        return prov.check_corpus(corpus, self.values if want is None else want)

    def assert_refused(self, recorded, want, field, where=''):
        """The deciding comparison refuses, and the problem text names `field`."""
        ok, problems, advisories = prov.compare(recorded, want)
        self.assertFalse(ok, f'{where}: accepted provenance that must be refused '
                             f'(recorded {recorded.get(field)!r}, now {want.get(field)!r}); '
                             f'problems={problems!r}')
        self.assertTrue(any(field in p for p in problems),
                        f'{where}: refused, but no problem names {field!r}: {problems!r}')
        self.assertEqual(advisories, [],
                         f'{where}: a deciding-field case produced advice, which is a silent '
                         f'acceptance of the deciding comparison: {advisories!r}')

    def assert_corpus_refused(self, corpus, needle, where='', want=None):
        """`check_corpus` refuses the directory, and the reason names `needle`."""
        ok, problems, advisories = self.check(corpus, want)
        self.assertFalse(ok, f'{where}: accepted a corpus that must be refused; '
                             f'problems={problems!r} advisories={advisories!r}')
        self.assertTrue(any(needle in p for p in problems),
                        f'{where}: refused without naming {needle!r}: {problems!r}')
        return problems


class MatchingProvenanceTests(ProvenanceBase):
    """Item 1: matching provenance is accepted -- the positive control."""

    def test_expected_carries_every_field_the_schema_names(self):
        self.assertEqual(sorted(self.values), sorted(FULL_FIELDS),
                         'expected() no longer produces exactly the schema fields')

    def test_render_block_round_trips_through_parse_block(self):
        blocks, problems = prov.parse_block(self.block)
        self.assertEqual(problems, [], f'rendering produced an unparsable block: {problems!r}')
        self.assertEqual(len(blocks), 1)
        self.assertEqual(blocks[0], self.values,
                         'render_block -> parse_block lost or reordered a value')

    def test_matching_provenance_is_accepted(self):
        ok, problems, advisories = prov.compare(self.values, self.values)
        self.assertTrue(ok, f'a block that matches itself was refused: {problems!r}')
        self.assertEqual(problems, [])
        self.assertEqual(advisories, [])

    def test_matching_corpus_directory_is_accepted(self):
        ok, problems, advisories = self.check(self.corpus('matching'))
        self.assertTrue(ok, f'a matching corpus directory was refused: {problems!r}')
        self.assertEqual(problems, [])
        self.assertEqual(advisories, [])

    def test_render_block_is_stable_and_refuses_an_incomplete_schema(self):
        self.assertEqual(prov.render_block(self.values), self.block,
                         'render_block is not deterministic: the block must be reproducible')
        for field in FULL_FIELDS:
            partial = {k: v for k, v in self.values.items() if k != field}
            with self.subTest(field=field):
                with self.assertRaises(prov.ProvenanceError):
                    prov.render_block(partial)


class MismatchRefusalTests(ProvenanceBase):
    """Item 2: every deciding field that moves is refused, naming itself."""

    def test_each_deciding_field_mismatch_is_refused_and_named(self):
        self.assertEqual(accepted(decision_cases(self.values), prov.compare), [],
                         'the shipped guard accepted a case that must be refused')
        for field in DECIDING_FIELDS:
            if field not in self.values:
                continue
            with self.subTest(field=field):
                want = dict(self.values)
                want[field] = f'moved-{field}'
                self.assert_refused(dict(self.values), want, field)

    def test_a_mismatch_is_refused_through_check_corpus(self):
        for field in DECIDING_FIELDS:
            if field not in self.values:
                continue
            with self.subTest(field=field):
                moved = dict(self.values, **{field: f'moved-{field}'})
                corpus = self.corpus(f'moved-{field}', c=corpus_c(moved),
                                     h=corpus_h(moved))
                self.assert_corpus_refused(corpus, field)

    def test_schema_mismatch_is_a_refusal_not_a_warning(self):
        """A block written by a schema this guard does not implement is refused."""
        recorded = dict(self.values, schema=str(int(self.values['schema']) + 1))
        self.assert_refused(recorded, dict(self.values), 'schema')

    def test_source_hashes_are_compared_one_by_one(self):
        """A single translator source moving must refuse on that source alone."""
        for name in prov.SOURCE_NAMES:
            field = f'source.{name}'
            with self.subTest(source=name):
                want = dict(self.values)
                want[field] = 'f' * 64
                ok, problems, _ = prov.compare(dict(self.values), want)
                self.assertFalse(ok)
                self.assertEqual(len(problems), 1, f'a single moved source reported '
                                                   f'{len(problems)} problems: {problems!r}')
                self.assertIn(field, problems[0])

    def test_real_toolkit_source_hashes_are_recomputed_not_trusted(self):
        """The three sources hash to the values `expected()` reports, from disk."""
        if not (TOOLKIT / 'src' / 'video' / prov.SOURCE_NAMES[0]).is_file():
            self.skipTest(f'the toolkit sources are not present at {TOOLKIT}')
        hashes = prov.source_hashes(TOOLKIT)
        self.assertEqual(sorted(hashes), sorted(prov.SOURCE_NAMES))
        for name, digest in hashes.items():
            with self.subTest(source=name):
                self.assertEqual(len(digest), 64)
                self.assertEqual(digest, prov.sha256_file(TOOLKIT / 'src' / 'video' / name))


class AdvisoryToolHashTests(ProvenanceBase):
    """Item 3: `tool.sha256` is recorded, reported, and never decisive."""

    def test_advisory_field_set_is_exactly_the_tool_hash(self):
        self.assertEqual(ADVISORY, ('tool.sha256',),
                         'the advisory set moved; if that was deliberate the fixture '
                         'must be re-derived with it')

    def test_a_different_tool_hash_is_accepted_with_an_advisory(self):
        recorded = dict(self.values, **{'tool.sha256': 'a' * 64})
        ok, problems, advisories = prov.compare(recorded, dict(self.values))
        self.assertTrue(ok, f'a differing tool hash refused a corpus that `just shaders` '
                            f'could have just produced: {problems!r}')
        self.assertEqual(problems, [])
        self.assertEqual(len(advisories), 1, f'expected exactly one advisory: {advisories!r}')
        self.assertIn('tool.sha256', advisories[0])
        self.assertIn('advisory', advisories[0])

    def test_a_different_tool_hash_is_accepted_through_check_corpus(self):
        recorded = dict(self.values, **{'tool.sha256': 'b' * 64})
        corpus = self.corpus('tool-hash', c=corpus_c(recorded), h=corpus_h(recorded))
        ok, problems, advisories = self.check(corpus)
        self.assertTrue(ok, f'refused on the tool hash alone: {problems!r}')
        self.assertEqual(problems, [])
        self.assertEqual(len(advisories), 2,
                         f'one advisory per file, since both record the hash: {advisories!r}')
        for advisory in advisories:
            self.assertIn('tool.sha256', advisory)

    def test_a_missing_tool_hash_is_also_not_a_refusal(self):
        """The advisory is reported, not demanded: an absent field is not a refusal."""
        recorded = {k: v for k, v in self.values.items() if k != 'tool.sha256'}
        ok, problems, advisories = prov.compare(recorded, dict(self.values))
        self.assertTrue(ok, f'a missing advisory field refused: {problems!r}')
        self.assertEqual(problems, [])

    def test_the_advisory_does_not_mask_a_deciding_difference(self):
        """A moved source plus a moved tool hash refuses on the source."""
        recorded = dict(self.values, **{'tool.sha256': 'c' * 64,
                                        'source.nv2a_vsh_hlsl.c': 'd' * 64})
        ok, problems, advisories = prov.compare(recorded, dict(self.values))
        self.assertFalse(ok, 'an advisory field absorbed a deciding difference')
        self.assertTrue(any('source.nv2a_vsh_hlsl.c' in p for p in problems), problems)
        self.assertEqual(len(advisories), 1)


class MissingFieldRefusalTests(ProvenanceBase):
    """Item 4: a block that lacks a deciding field is refused, naming that field."""

    def test_every_deciding_field_missing_in_turn_is_refused(self):
        for field in DECIDING_FIELDS:
            if field not in self.values:
                continue
            with self.subTest(field=field):
                recorded = {k: v for k, v in self.values.items() if k != field}
                self.assert_refused(recorded, dict(self.values), field)

    def test_a_missing_field_is_refused_through_check_corpus(self):
        text = corpus_c(self.values)
        for field in DECIDING_FIELDS:
            if field not in self.values:
                continue
            with self.subTest(field=field):
                corpus = self.corpus(f'no-{field}',
                                     c=without_field(text, field),
                                     h=corpus_h(self.values))
                self.assert_corpus_refused(corpus, field)

    def test_an_empty_block_is_refused_on_every_deciding_field(self):
        """The 'missing provenance became a pass' shape: markers present, nothing in them."""
        empty = f' * {prov.BEGIN_MARK}\n * {prov.END_MARK}'
        corpus = self.corpus('empty-block', c=corpus_c(self.values, body=empty),
                             h=corpus_h(self.values, body=empty))
        ok, problems, _ = self.check(corpus)
        self.assertFalse(ok, 'an empty provenance block was accepted')
        for field in DECIDING_FIELDS:
            if field not in self.values:
                continue
            with self.subTest(field=field):
                self.assertTrue(any(field in p for p in problems),
                                f'the empty block did not name {field!r}: {problems!r}')


class MalformedBlockTests(ProvenanceBase):
    """Item 5: a block the guard cannot read is a refusal, never a silent pass."""

    def test_begin_without_end_is_refused(self):
        body = '\n'.join(self.block.splitlines()[:-1])
        corpus = self.corpus('no-end', c=corpus_c(self.values, body=body))
        self.assert_corpus_refused(corpus, prov.END_MARK, 'begin without end')
        _, problems = prov.parse_block(corpus_c(self.values, body=body))
        self.assertTrue(any(prov.BEGIN_MARK in p and 'no' in p for p in problems), problems)

    def test_end_without_begin_is_refused(self):
        body = '\n'.join(self.block.splitlines()[1:])
        corpus = self.corpus('no-begin', c=corpus_c(self.values, body=body))
        self.assert_corpus_refused(corpus, prov.BEGIN_MARK, 'end without begin')
        _, problems = prov.parse_block(corpus_c(self.values, body=body))
        self.assertTrue(any(prov.END_MARK in p and prov.BEGIN_MARK in p for p in problems),
                        problems)

    def test_a_duplicate_key_is_refused(self):
        # The SAME value twice, so the only defect is the duplication: a naive reader
        # would let the second value win, and the guard must refuse rather than pick one.
        body = duplicate_field(self.block, 'dxc.version')
        corpus = self.corpus('duplicate-key', c=corpus_c(self.values, body=body))
        self.assert_corpus_refused(corpus, 'duplicate key', 'duplicate key')
        _, problems = prov.parse_block(corpus_c(self.values, body=body))
        self.assertTrue(any('dxc.version' in p for p in problems), problems)
        blocks, _ = prov.parse_block(corpus_c(self.values, body=body))
        self.assertEqual(blocks, [self.values],
                         'the duplicate left the parsed block disagreeing with the fields, '
                         'so this fixture would not isolate the duplicate-key refusal')

    def test_a_line_without_an_equals_sign_is_refused(self):
        lines = self.block.splitlines()
        body = '\n'.join(lines[:-1] + [' * source.nv2a_vsh_hlsl.c ' + 'e' * 64, lines[-1]])
        corpus = self.corpus('no-equals', c=corpus_c(self.values, body=body))
        self.assert_corpus_refused(corpus, 'key = value', 'line with no =')
        _, problems = prov.parse_block(corpus_c(self.values, body=body))
        self.assertTrue(any('not "key = value"' in p for p in problems), problems)

    def test_an_unknown_schema_value_is_refused(self):
        for unknown in ('2', '0', 'one'):
            with self.subTest(schema=unknown):
                recorded = dict(self.values, schema=unknown)
                corpus = self.corpus(f'schema-{unknown}', c=corpus_c(recorded),
                                     h=corpus_h(recorded))
                self.assert_corpus_refused(corpus, 'schema')

    def test_an_absent_block_is_refused(self):
        corpus = self.corpus('no-block', c='/*\n * The corpus, with no block at all.\n */\n'
                                            '#include "nv2a_vsh_programs.h"\n'
                                            'const size_t nv2a_vsh_program_count = 126;\n')
        self.assert_corpus_refused(corpus, 'records no provenance block', 'absent block')
        _, problems = prov.parse_block('/* nothing */\n')
        self.assertEqual(problems, [], 'a file with no block is not a parse problem; it is '
                                       'check_corpus\'s refusal to make')
        self.assertEqual(prov.parse_block('/* nothing */\n')[0], [])

    def test_a_field_outside_a_block_is_not_recorded(self):
        """A stray `key = value` in the corpus must not be read as provenance."""
        text = ('/*\n * schema = 1\n * dxc.version = not-a-real-record\n */\n'
                f'{corpus_c(self.values)}')
        blocks, problems = prov.parse_block(text)
        self.assertEqual(problems, [])
        self.assertEqual(len(blocks), 1)
        self.assertEqual(blocks[0], self.values,
                         'a stray line outside the markers was absorbed into the block')
        ok, _, _ = self.check(self.corpus('stray-line', c=text))
        self.assertTrue(ok, 'a stray line outside the markers changed the verdict')



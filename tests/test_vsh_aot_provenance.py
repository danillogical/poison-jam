def fake_dxc(tmp, lines):
    """A stand-in for dxc that exits or prints whatever `lines` says."""
    if os.name == 'nt':
        path = Path(tmp) / 'fake_dxc.bat'
        path.write_text('@echo off\r\n' + '\r\n'.join(lines) + '\r\n', encoding='utf-8')
    else:
        path = Path(tmp) / 'fake_dxc'
        path.write_text('#!/bin/sh\n' + '\n'.join(lines) + '\n', encoding='utf-8')
        path.chmod(0o755)
    return path


